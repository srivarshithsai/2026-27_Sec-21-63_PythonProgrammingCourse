#Membership operators
#IN operator
A='a' in 'apple'
print("result of a in apple," "is",A) 
A='x' in 'apple'
print("result of x in apple," "is",A)
#NOT IN operator
B={4,3,5,6}
result=4 not in B
print("result of 4 is not in",B,"is",result)
B={2,3,4,5}
result=5 in B
print("result of 5 in",B,"is",result)